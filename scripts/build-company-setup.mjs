import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

// Build a single transaction for the dashboard-only installation path.
// Keep the canonical migrations separate for reviewed operational upgrades.
const sources = ["supabase/schema.sql", "supabase/enterprise.sql"];
const inputs = sources.map((path) => readFileSync(path, "utf8"));
const hashes = inputs.map((sql, i) =>
  `-- ${sources[i]} SHA-256: ${createHash("sha256").update(sql).digest("hex")}`,
).join("\n");
const body = inputs.map((sql) => sql.replace(/^(?:begin|commit);\r?$/gm, "")).join("\n");
const output = `-- GENERATED by npm run build:company-sql. Do not edit this file directly.
-- Install ONLY in an empty Supabase test project, through its SQL Editor.
-- Existing application, Auth or storage records cause this installation to stop.
-- No users, billing, email, website configuration or production cutover is performed.
${hashes}
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
do $$
declare target record; populated boolean;
begin
 if to_regclass('auth.users') is null then
  raise exception 'This setup requires an empty Supabase project with managed Auth';
 end if;
 for target in
  select n.nspname as schema_name,c.relname as table_name
  from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where (n.nspname='public' and c.relkind in ('r','p','f'))
   or (n.nspname='auth' and c.relname='users' and c.relkind in ('r','p'))
   or (n.nspname='storage' and c.relname='objects' and c.relkind in ('r','p'))
 loop
  execute format('select exists(select 1 from %I.%I limit 1)',target.schema_name,target.table_name) into populated;
  if populated then
   raise exception 'Setup stopped: existing records detected. Use an empty test project; do not apply this bootstrap to your live database.';
  end if;
 end loop;
end $$;
${body}
do $$begin
 if not public.kl_enterprise_ready() then
  raise exception 'Company policy readiness failed; setup rolled back';
 end if;
end $$;
commit;
select public.kl_enterprise_ready() as database_ready;
`;
const destination = "supabase/company-setup.sql";
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== output) {
    console.error("Company setup SQL is stale. Run npm run build:company-sql.");
    process.exit(1);
  }
  console.log("PASS company setup SQL matches the canonical migrations");
} else {
  writeFileSync(destination, output);
  console.log(`Generated ${destination} for an empty test project`);
}
